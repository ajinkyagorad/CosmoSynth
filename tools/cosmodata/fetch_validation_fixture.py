#!/usr/bin/env python3
"""Build the JPL Horizons validation fixture used by the C# test suite.

The fixture answers two different questions, and keeping them apart matters:

1.  *Is our code correct?*  For each body we record JPL's own osculating elements at the
    reference epoch alongside the state vector they were derived from. Feeding that state
    into CosmoSynth.Core and comparing the recovered elements against JPL's is a check on
    our arithmetic with the physics held fixed — the two should agree to round-off.

2.  *How good is the physics model?*  We also record the true state at a series of later
    epochs. Propagating our two-body Kepler solution forward and comparing tells us how
    fast an unperturbed conic drifts away from the real, perturbed solar system. That
    number is a property of the model, not a bug, and the application is meant to display
    it honestly rather than pretend it is zero.

Run:  python3 tools/cosmodata/fetch_validation_fixture.py
Out:  tests/CosmoSynth.Core.Tests/fixtures/horizons_validation.json
"""

from __future__ import annotations

import argparse
import os
import sys
from typing import Any, Dict, List

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import horizons  # noqa: E402

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
DEFAULT_OUTPUT = os.path.join(
    REPO_ROOT, "tests", "CosmoSynth.Core.Tests", "fixtures", "horizons_validation.json"
)

START_TIME = "2026-01-01"
STOP_TIME = "2031-01-01"
STEP_SIZE = "73d"  # ~25 samples across five years

# Horizons rejects a zero-length interval, so a single-epoch query is expressed as a
# one-day window and only the first record is kept.
SINGLE_EPOCH_STOP = "2026-01-02"

# GM values are the DE440 system values already in CosmoSynth.Core.Constants, repeated here
# so the fixture is self-describing. The two-body mu for a heliocentric orbit is
# G(M_sun + M_planet), not GM_sun alone — an easy and surprisingly large mistake to make.
GM_SUN = 1.32712440041279419e11
GM_EARTH = 3.98600435507e5
GM_MOON = 4.902800118e3

# Horizons body codes. Codes 1-8 are planetary *system barycentres*: the right target for a
# heliocentric two-body fit, because the planet itself wobbles about the barycentre under
# the pull of its own moons. Using 399 (Earth's centre) instead of 3 (the Earth-Moon
# barycentre) injects a 4700 km monthly oscillation that has nothing to do with the Sun.
TARGETS: List[Dict[str, Any]] = [
    {"name": "Mercury", "command": "199", "center": "500@10", "gmCentral": GM_SUN, "gmBody": 2.2031868551e4},
    {"name": "Venus", "command": "299", "center": "500@10", "gmCentral": GM_SUN, "gmBody": 3.24858592e5},
    {"name": "EarthMoonBarycenter", "command": "3", "center": "500@10", "gmCentral": GM_SUN,
     "gmBody": GM_EARTH + GM_MOON},
    {"name": "MarsBarycenter", "command": "4", "center": "500@10", "gmCentral": GM_SUN, "gmBody": 4.2828375816e4},
    {"name": "JupiterBarycenter", "command": "5", "center": "500@10", "gmCentral": GM_SUN, "gmBody": 1.267127641e8},
    {"name": "SaturnBarycenter", "command": "6", "center": "500@10", "gmCentral": GM_SUN, "gmBody": 3.79405848418e7},
    {"name": "UranusBarycenter", "command": "7", "center": "500@10", "gmCentral": GM_SUN, "gmBody": 5.7945564e6},
    {"name": "NeptuneBarycenter", "command": "8", "center": "500@10", "gmCentral": GM_SUN, "gmBody": 6.83652710058e6},
    # The Moon about the Earth is included precisely because a two-body Kepler fit does
    # *badly* here: the Sun perturbs the lunar orbit strongly enough that osculating
    # elements are nearly meaningless over a month. Having the failure case in the fixture
    # stops anyone assuming the Kepler path is universally good enough.
    {"name": "Moon", "command": "301", "center": "500@399", "gmCentral": GM_EARTH, "gmBody": GM_MOON},
    # A main-belt asteroid, to exercise a moderately eccentric and inclined orbit.
    {"name": "Ceres", "command": "1;", "center": "500@10", "gmCentral": GM_SUN, "gmBody": 6.26325e1},
]


def build(output_path: str, delay: float) -> Dict[str, Any]:
    fixture: Dict[str, Any] = {
        "_comment": (
            "Generated by tools/cosmodata/fetch_validation_fixture.py from the JPL Horizons "
            "API. Vectors are geometric (no light-time correction) in the ICRF/J2000 "
            "equatorial frame; elements are in the ecliptic frame of J2000. Regenerate with "
            "that script; do not hand-edit."
        ),
        "source": "JPL Horizons (https://ssd.jpl.nasa.gov/horizons/)",
        "refPlaneVectors": "ICRF/J2000 equatorial",
        "refPlaneElements": "ecliptic and mean equinox of J2000",
        "startTime": START_TIME,
        "stopTime": STOP_TIME,
        "stepSize": STEP_SIZE,
        "bodies": [],
    }

    for index, target in enumerate(TARGETS):
        name = target["name"]
        print(f"[{index + 1}/{len(TARGETS)}] {name} ... ", end="", flush=True)

        vectors = horizons.fetch_vectors(
            body=target["command"],
            center=target["center"],
            start_time=START_TIME,
            stop_time=STOP_TIME,
            step_size=STEP_SIZE,
            ref_plane=horizons.REF_PLANE_ICRF,
        )
        horizons.polite_sleep(delay)

        elements = horizons.fetch_elements(
            body=target["command"],
            center=target["center"],
            start_time=START_TIME,
            stop_time=SINGLE_EPOCH_STOP,
            step_size="1d",
            ref_plane=horizons.REF_PLANE_ECLIPTIC,
        )
        horizons.polite_sleep(delay)

        fixture["bodies"].append(
            {
                "name": name,
                "horizonsCommand": target["command"],
                "center": target["center"],
                # The relative two-body problem is governed by the sum of the masses.
                "gravitationalParameter": target["gmCentral"] + target["gmBody"],
                "gmCentral": target["gmCentral"],
                "gmBody": target["gmBody"],
                "vectors": [sample.to_json() for sample in vectors],
                "elementsEcliptic": elements[0].to_json() if elements else None,
            }
        )
        print(f"{len(vectors)} vector samples, {len(elements)} element samples")

    os.makedirs(os.path.dirname(output_path), exist_ok=True)
    horizons.dump_json(output_path, fixture)
    return fixture


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", default=DEFAULT_OUTPUT, help="where to write the fixture JSON")
    parser.add_argument("--delay", type=float, default=horizons.DEFAULT_REQUEST_DELAY_SECONDS,
                        help="seconds to wait between Horizons requests")
    args = parser.parse_args()

    try:
        fixture = build(args.output, args.delay)
    except horizons.HorizonsError as exc:
        print(f"\nerror: {exc}", file=sys.stderr)
        return 1

    total = sum(len(body["vectors"]) for body in fixture["bodies"])
    print(f"\nWrote {args.output}")
    print(f"  {len(fixture['bodies'])} bodies, {total} state vectors")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
